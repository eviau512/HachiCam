param([string]$Glslc="$env:LOCALAPPDATA\Android\Sdk\ndk\30.0.16248370\shader-tools\windows-x86_64\glslc.exe")
$ErrorActionPreference='Stop'
$taskRoot=[IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$taskShaders=Join-Path $taskRoot 'app\src\main\cpp\shaders'
foreach($taskShader in @('local_support','local_ecc','noise_grid','color_merge','strong_selection','global_ecc','physical_check','regional_solver','observation_mapping')) {
& $Glslc '--target-env=vulkan1.0' '-O' (Join-Path $taskShaders "$taskShader.comp") '-o' (Join-Path $taskShaders "$taskShader.spv")
if($LASTEXITCODE -ne 0){throw 'Compute shader compilation failed'}
$taskBytes=[IO.File]::ReadAllBytes((Join-Path $taskShaders "$taskShader.spv"))
if($taskBytes.Length%4){throw 'Invalid SPIR-V byte count'}
$taskLines=[Collections.Generic.List[string]]::new()
$taskLines.Add("// Generated by scripts/build-compute-shaders.ps1; edit $taskShader.comp.")
$taskLines.Add('#pragma once')
$taskLines.Add('#include <cstdint>')
$taskLines.Add('#include <cstddef>')
$taskLines.Add("alignas(4) static const uint32_t $($taskShader)_spv[] = {")
for($taskAt=0;$taskAt -lt $taskBytes.Length;$taskAt+=32){
    $taskWords=@()
    for($taskI=$taskAt;$taskI -lt [Math]::Min($taskAt+32,$taskBytes.Length);$taskI+=4){
        $taskWords+=('0x{0:x8}' -f [BitConverter]::ToUInt32($taskBytes,$taskI))
    }
    $taskLines.Add('    '+($taskWords -join ', ')+',')
}
$taskLines.Add('};')
$taskLines.Add("static const size_t $($taskShader)_spv_size = sizeof($($taskShader)_spv);")
[IO.File]::WriteAllLines((Join-Path $taskShaders "$($taskShader)_spv.h"),$taskLines,[Text.UTF8Encoding]::new($false))
Write-Output "$taskShader shader: $($taskBytes.Length) bytes"
}
